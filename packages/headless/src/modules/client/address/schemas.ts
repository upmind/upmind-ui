import { compact, map, reduce } from "lodash-es";

import type { Address, AddressContext } from "./types";
import type { JsonSchema, UISchemaElement } from "@jsonforms/core";

export function useSchema({
  id,
  types,
  regions,
  baseModel,
  countries,
}: AddressContext): JsonSchema {
  const schema = {
    type: "object",
    title: "Address Fields",
    required: ["address1", "city", "countryId", "postcode", "type"],
    properties: {
      id: {
        type: ["string", "null"],
        title: "ID",
        description: "The AutoGenerated ID of this Address.",
        readOnly: true,
      },

      // ---
      address1: {
        type: "string",
      },

      address2: {
        type: ["string", "null"],
      },

      city: {
        type: "string",
        title: "City",
      },

      postcode: {
        type: "string",
        title: "Postcode",
      },

      regionId: {
        type: ["string", "null"],
        title: "Region",
        oneOf: !regions?.length
          ? undefined
          : map(regions, item => ({
              const: item.id,
              title: item.name,
            })),
      },

      countryId: {
        type: "string",
        title: "Country",
        default: baseModel?.countryId,
        oneOf: !countries?.length
          ? undefined
          : map(countries, item => ({
              const: item.id,
              title: item.name,
            })),
      },

      name: {
        type: ["string", "null"],
        title: "Name",
        default: baseModel?.name,
      },

      type: {
        type: "number",
        title: "Address Type",
        default: baseModel?.type,
        oneOf: !types?.length
          ? undefined
          : map(types, item => ({
              const: item.key,
              title: item.value,
            })),
      },
    },
  };

  if (id) {
    schema.required.push("name");
  }

  return schema as JsonSchema;
}

