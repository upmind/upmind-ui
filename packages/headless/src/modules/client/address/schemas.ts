// --- utils
import { get } from "lodash-es";
import type { JsonSchema, UISchemaElement } from "@jsonforms/core";
import { map } from "lodash-es";

// --- types
import { BrandConfigKeys } from "@upmind-automation/types";
import type { AddressContext } from "./types";

export function useSchema({
  types,
  regions,
  baseModel,
  countries,
  country,
  config,
}: AddressContext): JsonSchema {
  const schema = {
    type: "object",
    title: "Address Fields",
    properties: {
      id: {
        type: ["string", "null"],
        title: "ID",
        description: "The AutoGenerated ID of this Address.",
        readOnly: true,
      },

      address: {
        type: "object",
        title: "Address",
        default: {},
        required: ["address1", "city", "postcode", "countryId", "type"],
        properties: {
          address1: {
            type: "string",
            title: "Address",
          },

          address2: {
            type: ["string", "null"],
            title: "",
          },

          city: {
            type: "string",
            title: "City",
          },

          postcode: {
            type: "string",
            title: "Postal / Zip Code",
          },

          regionId: {
            type: ["string", "null"],
            title: "Region",
            oneOf: !regions?.length
              ? undefined
              : map(regions, item => ({
                  const: item.id,
                  title: item.name,
                })),
          },

          countryId: {
            type: "string",
            title: "Country",
            default: baseModel?.countryId,
            oneOf: !countries?.length
              ? undefined
              : map(countries, item => ({
                  const: item.id,
                  title: item.name,
                })),
          },

          phone: {
            type: "object",
            title: "Phone",
            isPhoneNumber: country?.code,
            properties: {
              number: {
                type: ["string", "null"],
                title: "Phone number ( with dialing code )",
              },

              nationalNumber: {
                type: ["string", "null"],
                title: "Phone number",
              },

              countryCallingCode: {
                type: ["string", "null"],
                title: "Country calling code",
              },

              country: {
                type: ["string", "null"],
                title: "Country",
              },
            },
          },

          type: {
            type: "number",
            title: "Address Type",
            default: baseModel?.type,
            oneOf: !types?.length
              ? undefined
              : map(types, item => ({
                  const: item.key,
                  title: item.value,
                })),
          },
        },
      },
    },
  };

  if (get(config, BrandConfigKeys.CHECKOUT_REQUIRE_PHONE)) {
    schema.properties.address.required.push("phone");
  }
  return schema as JsonSchema;
}

export function useUischema({ config }: AddressContext): UISchemaElement {
  const schema = {
    type: "VerticalLayout",
    elements: [
      {
        type: "Control",
        scope: "#/properties/address",
        options: {
          autoFocus: true,
          autocomplete: "off",
          detail: {
            type: "VerticalLayout",
            elements: [
              {
                type: "Control",
                scope: "#/properties/countryId",
              },
              {
                type: "address",
                options: {
                  fields: ["address1", "address2", "city", "postcode"],
                  placeholder: "Start typing your address",
                },
                elements: [
                  {
                    type: "Group",
                    options: {
                      border: false,
                    },
                    elements: [
                      {
                        type: "Control",
                        scope: "#/properties/address1",
                        options: {
                          placeholder: "House name, apartment number etc.",
                        },
                      },
                      {
                        type: "Control",
                        scope: "#/properties/address2",
                        options: {
                          placeholder: "Road, street name etc.",
                        },
                      },
                    ],
                  },
                  {
                    type: "Control",
                    scope: "#/properties/city",
                    options: {
                      placeholder: "City, town etc.",
                    },
                  },
                  {
                    type: "HorizontalLayout",
                    elements: [
                      {
                        type: "Control",
                        scope: "#/properties/regionId",
                        options: {
                          placeholder: "Select region",
                        },
                      },
                      {
                        type: "Control",
                        scope: "#/properties/postcode",
                        options: {
                          placeholder: "eg. 10011",
                        },
                      },
                    ],
                  },
                  {
                    type: "Control",
                    scope: "#/properties/phone",
                    rule: {
                      effect: "HIDE",
                      condition: get(
                        config,
                        BrandConfigKeys.CHECKOUT_REQUIRE_PHONE
                      )
                        ? { scope: "#", schema: { type: "null" } }
                        : { scope: "#", schema: { type: "object" } },
                    },
                  },
                ],
              },
            ],
          },
        },
      },
    ],
  };

  return schema as UISchemaElement;
}
