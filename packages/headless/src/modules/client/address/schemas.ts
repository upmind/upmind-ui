import { compact, get, map, reduce } from "lodash-es";

import { AddressTypes } from "./types";
import type { Address, AddressContext } from "./types";
import type { JsonSchema7, UISchemaElement } from "@jsonforms/core";
import { BrandConfigKeys } from "@upmind-automation/types";

export function useSchema({
  id,
  regions,
  baseModel,
  countries,
  config,
}: AddressContext): JsonSchema7 {
  const schema: JsonSchema7 = {
    type: "object",
    title: "Address",
    required: ["address1", "city", "countryId", "postcode"],
    properties: {
      id: {
        type: ["string", "null"],
        title: "ID",
        description: "The AutoGenerated ID of this Address.",
        readOnly: true,
      },

      // ---
      address1: {
        type: ["string"],
        title: "Address",
      },

      address2: {
        type: ["string", "null"],
        title: "",
      },

      city: {
        type: "string",
        title: "City",
      },

      postcode: {
        type: "string",
        title: "Postcode",
      },

      regionId: {
        type: ["string", "null"],
        title: "Region",
        oneOf: !regions?.length
          ? undefined
          : map(regions, item => ({
              const: item.id,
              title: item.name,
            })),
      },

      countryId: {
        type: "string",
        title: "Country",
        default: baseModel?.countryId,
        oneOf: !countries?.length
          ? undefined
          : map(countries, item => ({
              const: item.id,
              title: item.name,
            })),
      },

      name: {
        type: ["string", "null"],
        title: "Name",
        default: baseModel?.name,
      },

      type: {
        type: "number",
        title: "Address Type",
        default: baseModel?.type,
        oneOf: !AddressTypes?.length
          ? undefined
          : map(AddressTypes, item => ({
              const: item.key,
              title: item.value,
            })),
      },
    },
  };

  // ensure that id we are editing an existing address, that we require the name
  if (id) {
    schema.required!.push("name");
  }

  // ensure we honor the brand config
  if (get(config, BrandConfigKeys.REQUIRE_REGION_IN_ADDRESS)) {
    schema.required!.push("regionId");
  }

  return schema;
}

export function useUischema({
  id,
}: Partial<AddressContext> = {}): UISchemaElement {
  const schema = {
    type: "VerticalLayout",
    elements: [
      // ---
      {
        type: "VerticalLayout",
        elements: [
          {
            type: "Control",
            scope: "#/properties/countryId",
            options: {
              placeholder: "Please select a Country...",
            },
          },
          // ---
          {
            type: id ? "VerticalLayout" : "address",
            options: {
              fields: ["address1", "address2"],
              placeholder: "Start typing your address",
            },
            elements: [
              {
                type: "Group",
                options: {
                  border: false,
                },
                elements: [
                  {
                    type: "Control",
                    scope: "#/properties/address1",
                    options: {
                      placeholder: "House name, apartment number etc.",
                      autocomplete: "address-line1",
                    },
                  },
                  {
                    type: "Control",
                    scope: "#/properties/address2",
                    options: {
                      placeholder: "Road, street name etc.",
                      autocomplete: "address-line2",
                    },
                  },
                ],
              },
              {
                type: "Control",
                scope: "#/properties/city",
                options: {
                  placeholder: "City, town etc.",
                  autocomplete: "address-level2",
                },
              },
              {
                type: "HorizontalLayout",
                elements: [
                  {
                    type: "Control",
                    scope: "#/properties/regionId",
                    options: {
                      placeholder: "Select region",
                      autocomplete: "address-level1",
                    },
                  },
                  {
                    type: "Control",
                    scope: "#/properties/postcode",
                    options: {
                      placeholder: "eg. 10011",
                      autocomplete: "postal-code",
                    },
                  },
                ],
              },
            ],
          },
        ],
      },
    ],
  };

  return schema as UISchemaElement;
}
