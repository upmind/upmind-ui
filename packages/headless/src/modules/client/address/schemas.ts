import { compact, map, reduce } from "lodash-es";

import type { Address, AddressContext } from "./types";
import type { JsonSchema, UISchemaElement } from "@jsonforms/core";

export function useSchema({
  // TODO: country,
  types,
  regions,
  baseModel,
  countries,
  // ---
  places,
}: AddressContext): JsonSchema {
  const schema = {
    type: "object",
    title: "Address Fields",
    required: ["address1", "city", "countryId", "postcode", "type"],
    properties: {
      id: {
        type: ["string", "null"],
        title: "ID",
        description: "The AutoGenerated ID of this Address.",
        readOnly: true,
      },

      // ---

      place: {
        type: ["string", "null"],
        title: "Address",
        lookup: places?.search,
      },

      manualPlace: {
        type: ["boolean", "null"],
        title: "Can't see your address?",
        default: baseModel?.manualPlace,
        readOnly: true,
      },

      // ---
      address1: {
        type: "string",
        title: "Address Line 1",
      },

      address2: {
        type: ["string", "null"],
        title: "Address Line 2",
      },

      city: {
        type: "string",
        title: "City",
      },

      postcode: {
        type: "string",
        title: "Postcode",
      },

      regionId: {
        type: ["string", "null"],
        title: "Region",
        oneOf: !regions?.length
          ? undefined
          : map(regions, item => ({
              const: item.id,
              title: item.name,
            })),
      },

      // not sure if this is ever used, but it is in the type definition
      state: {
        type: ["string", "null"],
        title: "State",
      },

      countryId: {
        type: "string",
        title: "Country",
        default: baseModel?.countryId,
        oneOf: !countries?.length
          ? undefined
          : map(countries, item => ({
              const: item.id,
              title: item.name,
            })),
      },

      // ---

      name: {
        type: ["string", "null"],
        title: "Name",
        default: baseModel?.name,
      },
      // ---

      default: {
        type: ["boolean", "null"],
        title: "Make this the default address?",
      },

      type: {
        type: "number",
        title: "Address Type",
        default: baseModel?.type,
        oneOf: !types?.length
          ? undefined
          : map(types, item => ({
              const: item.key,
              title: item.value,
            })),
      },
    },
  };

  // if (id) {
  //   schema.required.push("name");
  //   schema.required.push("type");
  // }

  return schema as JsonSchema;
}

export function useUischema({ addresses }: any): UISchemaElement {
  const lookups = {
    addresses: reduce(
      addresses,
      (result: { value: string; label: string }[], item: Address) => {
        // Only return actual addresses, NOT companies
        if (!item?.companyDetails) {
          result.push({
            value: item.id,
            label: [
              item.name,
              item.address1,
              item.address2,
              item.city,
              item.postcode,
            ].join(", "),
          });
        }

        return result;
      },
      []
    ),
  };

  const schema = {
    type: "VerticalLayout",
    elements: [
      {
        type: "Control",
        scope: "#/properties/name",
        options: {
          autoFocus: true,
          autocomplete: "off",
          placeholder: "My home address, etc...",
        },
        rule: {
          effect: "SHOW",
          condition: {
            scope: "#",
            schema: {
              required: ["id"],
            },
          },
        },
      },

      // ---
      {
        type: "Control",
        scope: "#/properties/place",
        i18n: "client.unified.form.fields.place",
        options: {
          autoFocus: true,
          icon: "search",
          autocomplete: "off",
          align: "start",
          side: "bottom",
          placeholder: "Search for address ...",
          items: compact([
            lookups.addresses?.length
              ? {
                  label: "Your saved addresses",
                  i18n: "client.unified.form.fields.saved",
                  as: "separator",
                }
              : null,
            ...lookups.addresses,
            // {
            //   label: "Enter manually",
            //   i18n: "client.unified.form.fields.manual",
            //   value: "manual",
            //   as: "button",
            //   variant: "link",
            //   size: "sm",
            //   persist: true,
            // },
          ]),
        },
        rule: {
          effect: "HIDE",
          condition: {
            scope: "#",
            schema: {
              anyOf: [
                { required: ["id"] },
                {
                  required: ["place"],
                  properties: { place: { const: "manual" } },
                },
              ],
            },
          },
        },
      },

      // ---
      {
        type: "VerticalLayout",
        elements: [
          {
            type: "Control",
            scope: "#/properties/address1",
            label: "Address", // ensure we  show the title for BOTH address fields
            options: {
              autoFocus: true,
              autocomplete: "address-line1",
              placeholder: "Address first line...",
            },
          },
          {
            type: "Control",
            scope: "#/properties/address2",
            label: "", // ensure we DON'T show the title
            options: {
              autocomplete: "address-line2",
              placeholder: "Address second line...",
              class: "-mt-8",
            },
          },

          // ---
          {
            type: "HorizontalLayout",
            elements: [
              {
                type: "Control",
                scope: "#/properties/city",
                options: {
                  autocomplete: "address-level2",
                  placeholder: "City...",
                },
              },
              {
                type: "Control",
                scope: "#/properties/postcode",
                options: {
                  autocomplete: "postal-code",
                  placeholder: "Postcode...",
                },
              },
            ],
          },
          // ---
          {
            type: "Control",
            scope: "#/properties/regionId",
            options: {
              autocomplete: "address-level1",
              placeholder: "Please select a Region...",
            },
          },
          {
            type: "Control",
            scope: "#/properties/countryId",
            options: {
              autocomplete: "country",
              placeholder: "Please select a Country...",
            },
          },
        ],
        rule: {
          effect: "SHOW",
          condition: {
            scope: "#/properties/manualPlace",
            schema: { const: true },
          },
        },
      },

      // ---
      // We don't ever show this field as it is set by an action
      // {
      //   type: "Control",
      //   scope: "#/properties/default",
      //   options: {
      //     // toggle: true
      //   }
      // }
    ],
  };

  return schema as UISchemaElement;
}
