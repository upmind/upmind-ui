// --- utils
import { map } from "lodash-es";

// --- types
import type { CompanyContext } from "./types";
import type { JsonSchema, UISchemaElement } from "@jsonforms/core";

export const useSchema = ({
  emails,
  phones,
  addresses,
  baseModel,
}: CompanyContext) => {
  const choices = {
    emails: emails?.getAllFromCache(),
    phones: phones?.getAllFromCache(),
    addresses: addresses?.getAllFromCache(),
  };

  const schema = {
    type: "object",
    title: "Address Fields",
    required: ["name", "addressId", "emailId"],
    properties: {
      id: {
        type: ["string", "null"],
        title: "ID",
        description: "The AutoGenerated ID of this Company.",
        readOnly: true,
      },

      // ---
      name: {
        type: "string",
        title: "Name",
      },

      addressId: {
        type: "string",
        title: "Address",
        default: baseModel.addressId,
        oneOf: !choices?.addresses?.length
          ? undefined
          : map(choices.addresses, item => ({
              const: item.id,
              title: item.name,
            })),
        lookup: addresses?.filter,
      },

      emailId: {
        type: "string",
        title: "Email",
        default: baseModel.emailId,
        oneOf: !choices?.emails?.length
          ? undefined
          : map(choices.emails, item => ({
              const: item.id,
              title: item.email,
            })),
        lookup: emails?.filter,
      },

      phoneId: {
        type: "string",
        title: "Phone",
        default: baseModel.phoneId,
        oneOf: !choices?.phones?.length
          ? undefined
          : map(choices.phones, item => ({
              const: item.id,
              title: item.nationalNumber,
            })),
        lookup: phones?.filter,
      },

      regNumber: {
        type: ["string", "null"],
        title: "Registration number",
      },
      vatNumber: {
        type: ["string", "null"],
        title: "Registered tax/VAT id",
      },
      // vatPercent: {
      //   type: ["string", "null"],
      //   title: "VAT percent",
      // },

      // ---

      default: {
        type: ["boolean", "null"],
        title: "Make this the default company?",
      },
    },
  };

  // if (id) {
  //   schema.required.push("name");
  //   schema.required.push("type");
  // }

  return schema as JsonSchema;
};

