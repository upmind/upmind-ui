import { useClientAddresses, useClientAddress } from "../address";
import {
  useSchema as useAddressSchema,
  useUischema as useAddressUischema,
} from "../address/schemas";

// --- types
import { BrandConfigKeys } from "@upmind-automation/types";
import type { CompanyContext } from "./types";
import type { JsonSchema7, Layout, UISchemaElement } from "@jsonforms/core";

export const useSchema = ({
  clientId,
  countries,
  country,
  regions,
  baseModel,
  config,
}: CompanyContext): JsonSchema7 => {
  const schema: JsonSchema7 = {
    type: "object",
    title: "Company",
    required: ["name"],
    properties: {
      id: {
        type: ["string", "null"],
        title: "ID",
        description: "The AutoGenerated ID of this Company.",
        readOnly: true,
      },
      name: {
        type: "string",
        title: "Company Name",
      },
      regNumber: {
        type: ["string", "null"],
        title: "Company Number",
      },
      vatNumber: {
        type: ["string", "null"],
        title: "Registered Tax ID",
      },

      emailId: {
        type: ["string", "null"],
        title: "Email",
        default: baseModel?.emailId,
      },
      phoneId: {
        type: ["string", "null"],
        title: "Phone",
        default: baseModel?.phoneId,
      },
    },
    // this is where we conditionally allow either an existing addressId or a new address object
    oneOf: [
      {
        type: "object",
        title: "Existing Address",
        description: "Select an existing address for this company.",
        required: ["addressId"],
        properties: {
          addressId: {
            type: ["string", "null"],
            title: "Address",
            default: baseModel?.addressId,
          },
        },
      },
      {
        type: "object",
        title: "New Address",
        description: "Create a new address for this company.",
        required: ["address"],
        properties: {
          address: useAddressSchema({
            clientId,
            regions,
            baseModel: {
              countryId: country?.id,
            },
            countries,
            config,
          }),
        },
      },
    ],
  };

  return schema;
};

export const useUischema = ({ model }: CompanyContext) => {
  const uiSchema = {
    type: "VerticalLayout",
    elements: [
      {
        type: "Control",
        scope: "#/properties/name",
        options: {
          autoFocus: true,
          autocomplete: "off",
          placeholder: "My company name",
        },
      },
      {
        type: "HorizontalLayout",
        elements: [
          {
            type: "Control",
            scope: "#/properties/regNumber",
            options: {
              placeholder: "Registered tax or GST",
            },
          },
          {
            type: "Control",
            scope: "#/properties/vatNumber",
            options: {
              placeholder: "VAT Number",
            },
          },
        ],
      },
    ],
  };

  // this is where we conditionally render either an existing addressId or a new address uiSchema
  if (!model?.addressId) {
    debugger;
    uiSchema.elements.push({
      type: "VerticalLayout",
      elements: [
        {
          type: "Control",
          scope: "#/properties/address",
          options: {
            autoFocus: true,
            autocomplete: "off",
            detail: useAddressUischema(),
          },
        },
      ],
    } as any);
  } else {
    debugger;
    uiSchema.elements.push({
      type: "Manager",
      scope: "#/properties/addressId",
      options: {
        manage: {
          list: useClientAddresses,
          mutate: useClientAddress,
        },
        clientId: "todo-123456",
      },
    } as any);
  }

  return uiSchema as UISchemaElement;
};
