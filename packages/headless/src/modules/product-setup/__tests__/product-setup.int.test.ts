describe("useProductSetup — invalid-basket integration (FE-2796)", () => {
  beforeEach(() => {
    clearSessionCookies();
    useSessionStore().useActions().clear();
    useProductSetup().reset();
  });

  afterEach(() => {
    vi.restoreAllMocks();
    useProductSetup().reset();
  });

  // --- routing ----------------------------------------------------------------

  describe("getNextRelated / getNextInvalid — routing", () => {
    // Unblocked by the CONFIGURED cross-referenced capture: the hosting product's
    // `domain` provisionField holds DOMAIN_ORG's service_identifier, and that
    // domain is invalid — the exact cross-reference getNextRelated walks.
    it("routes to the basket item whose service_identifier is referenced by the actor's provisionFields AND which itself has errors", async () => {
      const { ids } = await bootConfiguredBasket();
      const setup = useProductSetup();
      await setup.isReady();

      // The ACTOR is the hosting product; its provisionFields reference the
      // .org domain's service_identifier (fixturegenbeta.org).
      const hostingConfig = await setup.configure(ids.hosting);
      const related = setup.getNextRelated(hostingConfig.service);

      expect(related, "a related basket item was found").toBeDefined();
      // getNextRelated returns the DOMAIN whose service_identifier the hosting
      // references — not the hosting product itself.
      expect(related!.id).toBe(ids.domainB);
      expect(related!.serviceIdentifier).toBe(ids.domainBService);
      // and that referenced domain really does still have errors.
      expect(related!.errors, "the referenced domain has errors").not.toEqual(
        []
      );
    });

    // Unblocked by the same capture: getNextRelated resolves the referenced
    // .org domain (products[1]) while getNextInvalid resolves the first
    // setup-requiring product (products[0], the .au domain) — so the two differ,
    // letting us prove getNextRequiringSetup prefers the related one.
    it("getNextRequiringSetup prioritises a related product (getNextRelated) over a merely-invalid one (getNextInvalid)", async () => {
      const { ids } = await bootConfiguredBasket();
      const setup = useProductSetup();
      await setup.isReady();

      const hostingConfig = await setup.configure(ids.hosting);

      const related = setup.getNextRelated(hostingConfig.service);
      const invalid = setup.getNextInvalid(hostingConfig.service);
      const requiring = setup.getNextRequiringSetup(hostingConfig.service);

      // The two routing strategies resolve DIFFERENT products for this actor…
      expect(related!.id).toBe(ids.domainB);
      expect(invalid!.id).toBe(ids.domainA);
      expect(requiring!.id).not.toBe(invalid!.id);
      // …and getNextRequiringSetup prefers the related one.
      expect(requiring!.id).toBe(related!.id);
    });

    // BLOCKED (headless core bug, NOT a capture gap): `getNextInvalid` rejects on
    // a TOP-LEVEL `productId` that `BasketProduct` exposes under
    // `.configuration.productId`, so the reject is inert and it always returns
    // `first(products)` — including the actor's own product. That cannot be
    // asserted green from the test layer without weakening the contract or
    // editing read-only headless source. The actor-exclusion PROOF lives in the
    // lane (c) unit `useProductSetup.getNextInvalid.test.ts` (committed `it.fails`),
    // and the one-line fix is staged at `docs/plans/fe2796-getnextinvalid.patch`.
    // Once that patch lands, drop `.fails` there and promote this integration
    // todo (the configured capture already seats two DISTINCT-productId invalid
    // domains — bpids domainA/domainB above — ready to drive it).
    it.todo(
      "getNextInvalid returns the next product requiring setup, excluding the actor's own product"
    );

    it("getNextRelated returns undefined when the actor's provisionFields reference no other basket item", async () => {
      await bootInvalidBasket();
      const setup = useProductSetup();
      await setup.isReady();

      const actorProduct = setup.products.value[0];
      const config = await setup.configure(actorProduct.id);

      // The actor is a CONFIGURABLE domain: its provisionFields are non-empty
      // (registrant keys) — so this exercises the real matching branch, not the
      // isEmpty early-return. No basket item's service_identifier is referenced,
      // so the result is undefined.
      const related = setup.getNextRelated(config.service);
      expect(related).toBeUndefined();
    });
  });

  // --- apply / updateMany -----------------------------------------------------

  describe("apply — updateMany merge semantics", () => {
    // Unblocked by the CONFIGURED capture: two invalid domains with DISTINCT
    // non-null service_identifiers (their slds) and overlapping registrant error
    // paths — so configuring one selects the other as a "similar" product.
    it("limits selected 'similar' products to provisionFields ONLY — term/quantity/options/attributes never propagate across products", async () => {
      const spy = vi
        .spyOn(basketProductServices, "updateMany")
        .mockResolvedValue({} as never);

      const { basket, ids } = await bootConfiguredBasket();
      const setup = useProductSetup();
      await setup.isReady();

      const current = setup.products.value.find(p => p.id === ids.domainA)!;
      const similarBefore = basket.products.value!.find(
        p => p.id === ids.domainB
      )!;
      const similarTerm = similarBefore.configuration.term;
      const similarQuantity = similarBefore.configuration.quantity;

      await setup.configure(current.id);
      // The other configured domain is captured as similar and auto-selected.
      expect(setup.similarProducts.value.map(p => p.id)).toEqual([ids.domainB]);
      expect(setup.selected.value).toContain(ids.domainB);

      await setup.apply(REGISTRANT_MODEL);

      const payload = spy.mock.calls[0][1] as BasketProduct[];
      const similarPayload = payload.find(p => p.id === ids.domainB);
      expect(similarPayload).toBeDefined();

      // provisionFields the user filled DO propagate to the similar product…
      expect(
        similarPayload!.configuration.provisionFields.update_registrant_name
      ).toBe(REGISTRANT_MODEL.provisionFields.update_registrant_name);
      // …but term / quantity never do — the similar product keeps its own.
      expect(similarPayload!.configuration.term).toBe(similarTerm);
      expect(similarPayload!.configuration.quantity).toBe(similarQuantity);
      // and its OWN sld survives — the current product's sld never leaked across
      // (provisionFields only FILL holes on similars, they never clobber).
      expect(similarPayload!.configuration.provisionFields.sld).toBe(SLD_B);
      expect(similarPayload!.configuration.provisionFields.sld).not.toBe(SLD_A);
    });

    it("merges the current product's delta over its existing config — the user's submitted provision values win", async () => {
      const spy = vi
        .spyOn(basketProductServices, "updateMany")
        .mockResolvedValue({} as never);

      await bootInvalidBasket();
      const setup = useProductSetup();
      await setup.isReady();

      const current = setup.products.value[0];
      await setup.configure(current.id);
      expect(
        setup.schema.value,
        "invalid schema captured at configure"
      ).toBeTruthy();

      await setup.apply(REGISTRANT_MODEL);

      expect(spy).toHaveBeenCalledTimes(1);
      const payload = spy.mock.calls[0][1] as BasketProduct[];
      const currentPayload = payload.find(p => p.id === current.id);
      expect(currentPayload).toBeDefined();
      // The user's submitted registrant values are present on the current product.
      expect(
        currentPayload!.configuration.provisionFields.update_registrant_name
      ).toBe(REGISTRANT_MODEL.provisionFields.update_registrant_name);
      expect(
        currentPayload!.configuration.provisionFields.update_registrant_email
      ).toBe(REGISTRANT_MODEL.provisionFields.update_registrant_email);
    });

    it("calls updateMany with a full-basket REPLACE payload — every basket product is re-listed so none is silently dropped", async () => {
      const spy = vi
        .spyOn(basketProductServices, "updateMany")
        .mockResolvedValue({} as never);

      const basket = await bootInvalidBasket();
      const setup = useProductSetup();
      await setup.isReady();

      const current = setup.products.value[0];
      await setup.configure(current.id);
      await setup.apply(REGISTRANT_MODEL);

      expect(spy).toHaveBeenCalledTimes(1);
      const payload = spy.mock.calls[0][1] as BasketProduct[];
      // REPLACE: the payload re-lists EVERY basket product (not just the edited).
      expect(payload).toHaveLength(basket.products.value!.length);
      const ids = payload.map(p => p.id).sort();
      const basketIds = basket.products.value!.map(p => p.id).sort();
      expect(ids).toEqual(basketIds);
    });

    it("asserts the outgoing updateMany request body against a real basket (contract-level, not merge eyeballed through the browser)", async () => {
      const spy = vi
        .spyOn(basketProductServices, "updateMany")
        .mockResolvedValue({} as never);

      const basket = await bootInvalidBasket();
      const setup = useProductSetup();
      await setup.isReady();

      const current = setup.products.value[0];
      await setup.configure(current.id);
      await setup.apply(REGISTRANT_MODEL);

      // The collaborator seam is called with the live basket id and the full
      // product array — the contract the browser flow depends on.
      const [basketId, payload, models] = spy.mock.calls[0] as [
        string,
        BasketProduct[],
        unknown[]
      ];
      expect(basketId).toBe(basket.basketId.value);
      expect(Array.isArray(payload)).toBe(true);
      expect(payload.length).toBeGreaterThan(0);
      expect(models).toEqual([]);
    });

    it("leaves products that are NOT in [bpid, ...selected] untouched in the updateMany payload", async () => {
      const spy = vi
        .spyOn(basketProductServices, "updateMany")
        .mockResolvedValue({} as never);

      await bootInvalidBasket();
      const setup = useProductSetup();
      await setup.isReady();

      const current = setup.products.value[0];
      const untouched = setup.products.value[1];
      await setup.configure(current.id);
      // No similars for a null-service_identifier domain, so selected is empty:
      expect(setup.selected.value).toEqual([]);

      await setup.apply(REGISTRANT_MODEL);

      const payload = spy.mock.calls[0][1] as BasketProduct[];
      const untouchedPayload = payload.find(p => p.id === untouched.id);
      expect(untouchedPayload).toBeDefined();
      // The untouched product carries none of the current product's submitted
      // registrant values — it passed through verbatim.
      expect(
        untouchedPayload!.configuration.provisionFields?.update_registrant_name
      ).not.toBe(REGISTRANT_MODEL.provisionFields.update_registrant_name);
    });
  });

  // --- reset lifecycle --------------------------------------------------------

  describe("reset — singleton lifecycle", () => {
    it("clears module-level bpid/schema/uischema/similarProducts/selected on reset()", async () => {
      await bootInvalidBasket();
      const setup = useProductSetup();
      await setup.isReady();

      const current = setup.products.value[0];
      await setup.configure(current.id);
      // Populated by configure() on an invalid product.
      expect(setup.schema.value).toBeTruthy();
      expect(setup.uischema.value).toBeTruthy();

      setup.reset();

      expect(setup.schema.value).toBeUndefined();
      expect(setup.uischema.value).toBeUndefined();
      expect(setup.similarProducts.value).toEqual([]);
      expect(setup.selected.value).toEqual([]);
    });

    // STILL BLOCKED (needs a richer capture than this one): proving a fresh
    // *schema* on re-entry needs two invalid products with DIFFERENT invalid
    // schemas. The `case=related-host` fixtures now dispatch the hosting config
    // by bpid (so per-product blueprints no longer collapse to one identity — the
    // original blocker), BUT the two INVALID products in this capture are both
    // domains sharing the identical registrant schema, and the hosting product is
    // VALID (empty invalid schema). So a re-entry between them cannot exhibit a
    // DISTINCT non-empty schema. (Fresh *similarProducts* on re-entry IS now
    // proven — see the sibling "no residual similarProducts" test.)
    // NEXT SEED: two INVALID products of different types with disjoint error
    // field sets (e.g. a domain missing registrant + a hosting product missing a
    // required field), so their invalid schemas differ.
    it.todo(
      "configure() re-entry after reset() captures a fresh schema + similarProducts for the new bpid — no stale state leaks from the previous product"
    );

    // Unblocked by the CONFIGURED capture: two invalid domains that are each
    // other's "similar" product, so a partial cycle leaves a non-empty
    // similarProducts that reset() must clear before the next product.
    it("a partial configure() -> (no apply) -> reset() cycle leaves no residual similarProducts for the next product set up", async () => {
      const { ids } = await bootConfiguredBasket();
      const setup = useProductSetup();
      await setup.isReady();

      // First product: configuring DOMAIN_AU selects DOMAIN_ORG as similar.
      await setup.configure(ids.domainA);
      expect(setup.similarProducts.value.map(p => p.id)).toEqual([ids.domainB]);

      // Abandon without applying.
      setup.reset();
      expect(setup.similarProducts.value).toEqual([]);
      expect(setup.selected.value).toEqual([]);

      // Re-entry for the OTHER product: similarProducts now reflects the NEW
      // product's similars (DOMAIN_AU) with no residual DOMAIN_ORG entry leaking
      // from the abandoned cycle.
      await setup.configure(ids.domainB);
      expect(setup.similarProducts.value.map(p => p.id)).toEqual([ids.domainA]);
      expect(setup.similarProducts.value.map(p => p.id)).not.toContain(
        ids.domainB
      );
    });
  });
});
