/**
 * @fileoverview useProductSetup integration — getNextRelated/getNextInvalid
 * routing, apply()/updateMany merge semantics, and reset() lifecycle (FE-2796)
 *
 * ## Job To Be Done
 * FE-2457's product-setup flow is well covered at e2e; the remaining gaps are
 * load-bearing wiring that belongs at integration (ADR 021). Three behaviours:
 *
 *   1. `getNextRelated` / `getNextInvalid` routing — `getNextInvalid` returns
 *      the next product requiring setup, excluding the actor's own; `getNextRelated`
 *      walks the actor's `provisionFields` for a value matching another basket
 *      item's `service_identifier` (that item having errors), and
 *      `getNextRequiringSetup = getNextRelated || getNextInvalid` prefers the
 *      related one.
 *   2. `apply()` / `updateMany` merge semantics (highest silent-data-loss risk)
 *      — the current product receives the full delta merged over its existing
 *      config; selected "similar" products receive `provisionFields` ONLY; the
 *      `updateMany` call is a full-basket REPLACE, so every product must be
 *      re-listed or it is dropped. The contract under test is the OUTGOING
 *      `updateMany` request body, asserted against a real basket.
 *   3. `reset()` singleton lifecycle — the module-level state
 *      (`bpid`/`schema`/`uischema`/`similarProducts`/`selected`) is a singleton;
 *      it must clear on `reset()`.
 *
 * ## Unblocked by the FE-2937 headless generator (this worktree)
 * These were `it.todo` blocked on FE-2784's invalid-basket seeding rails: no
 * recorded basket body carried a product with validation `errors` +
 * `provisionFields`, and integration is fixtures-only (never the real API) and
 * may not fabricate domain data (ADR 021 §Core Principle 3). That fixture now
 * EXISTS — `./fixtures/` was generated by `product-setup.fixtures.ts` driving a
 * REAL guest storefront flow on staging in headless chromium (FE-2937 mode (b)),
 * seating TWO bare configurable domains so the `PATCH …/provision_fields/values/
 * check` returns a 409 whose per-field errors become the basket's `basketErrors`.
 * The tests below drive the REAL `useProductSetup` over that fixture via MSW
 * replay (`setup.integration.ts`); the assertions come from the FE-2796/FE-2457
 * spec, not from reading `useProductSetup.ts`.
 *
 * ## Two captures back these tests
 * 1. The two-BARE-domain basket (above) — invalid domains with NULL
 *    `service_identifier`, driving the apply()/updateMany merge + REPLACE
 *    contract and the reset() clear.
 * 2. A CONFIGURED cross-referenced basket — two invalid domains each given an
 *    `sld` (so each carries a DISTINCT non-null `service_identifier`) plus a
 *    valid hosting product whose `domain` provisionField references DOMAIN_ORG's
 *    service_identifier. This is the seam getNextRelated / getNextRequiringSetup
 *    and the "similar products" propagation need. It lives beside the bare
 *    capture under synthetic `case=` fixture identities (the discrimination
 *    session-store uses), wired onto the live routes by `bootConfiguredBasket`
 *    — the per-product endpoints dispatched by recorded bpid so the id-masked
 *    identity does not collapse them.
 *
 * ## What is now live, and what stays blocked
 * 10 of the 12 are live. Two remain `it.todo`, each with a precise tag:
 *   - `getNextInvalid` actor-exclusion — a headless CORE bug (reject keys on a
 *     top-level `productId` that lives under `.configuration.productId`), NOT a
 *     capture gap. Proof + staged fix live in the lane (c) unit
 *     `useProductSetup.getNextInvalid.test.ts` + `docs/plans/fe2796-getnextinvalid.patch`.
 *   - fresh-DISTINCT-schema on configure() re-entry — needs two invalid products
 *     with DIFFERENT invalid schemas; this capture's two invalid products are
 *     both domains (identical registrant schema). Fresh similarProducts on
 *     re-entry IS proven.
 */

