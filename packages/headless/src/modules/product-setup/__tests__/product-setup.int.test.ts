// Fields the 409 provision-check rejected on each bare domain — the invalid
// schema `configure()` captures is scoped to exactly these, so a model that
// fills them produces a non-empty `apply()` delta.
const REGISTRANT_MODEL = {
  provisionFields: {
    sld: "fixturegen-example",
    update_registrant_name: "Fixture Gen",
    update_registrant_organisation: "Fixture Org",
    update_registrant_email: "fixturegen@example.com",
    update_registrant_phone: "+15551234567",
    update_registrant_address_1: "1 Fixture Way",
    update_registrant_address_city: "Testville",
    update_registrant_address_postcode: "TE5 7ER",
    update_registrant_address_country_code: "GB"
  }
} as const;

/**
 * Boot a real guest session and settle the real `useBasket` machine over the
 * replayed invalid basket — the same live-machine drive the pilot journey uses,
 * but seeded from THIS module's own capture (no empty-basket override: the
 * recorded `orders/current` already carries the two invalid domains).
 */
async function bootInvalidBasket(): Promise<UseBasket> {
  await useSessionStore().useActions().isReady();
  const basket = useBasket();
  basket.clear();
  const settled = await basket.isReady();
  if (!settled) {
    throw new Error(
      `bootInvalidBasket: useBasket did not settle (state: ${JSON.stringify(
        basket.state.value.value
      )})`
    );
  }
  return basket;
}

/**
 * The bpids of the three products in the CONFIGURED cross-referenced basket, in
 * captured order: two invalid domains carrying distinct non-null
 * `service_identifier`s (from their slds) and a valid hosting product whose
 * `domain` provisionField references DOMAIN_ORG's service_identifier.
 */
interface ConfiguredIds {
  domainA: string; // .au, service_identifier fixturegenalpha.au, invalid
  domainB: string; // .org, service_identifier fixturegenbeta.org, invalid
  hosting: string; // references domainB's service_identifier, valid
  hostingProduct: string; // the hosting product_id (for its provision-field defs)
  domainBService: string; // fixturegenbeta.org
}

/**
 * Boot the CONFIGURED cross-referenced basket (FE-2796 second capture).
 *
 * The base `orders/current` / `check` / per-product fixtures describe the
 * two-BARE-domain basket; the configured basket lives alongside them under
 * synthetic `case=` fixture identities (the same discrimination session-store
 * uses) so it never collides on disk. This helper wires those `case=` bodies
 * onto the routes the live machines actually call (which carry no `case` param),
 * dispatching the per-product endpoints by the recorded bpid, then settles the
 * REAL `useBasket` machine over them. No domain data is fabricated — every body
 * is a real capture loaded via `getFixtureBody`.
 */
async function bootConfiguredBasket(): Promise<{
  basket: UseBasket;
  ids: ConfiguredIds;
}> {
  const currentBody = getFixtureBody<{
    data: {
      products: Array<{
        id: string;
        product_id: string;
        service_identifier: string;
      }>;
    };
  }>("get-orders-current-case-related", { recordingsDir });
  const products = currentBody.data.products;
  const ids: ConfiguredIds = {
    domainA: products[0].id,
    domainB: products[1].id,
    hosting: products[2].id,
    hostingProduct: products[2].product_id,
    domainBService: products[1].service_identifier
  };

  const checkBody = getFixtureBody(
    "patch-orders-id-provision-fields-values-check-case-related",
    { recordingsDir }
  );
  const valuesA = getFixtureBody(
    "get-orders-id-products-id-provision-fields-values-case-related-a",
    { recordingsDir }
  );
  const valuesB = getFixtureBody(
    "get-orders-id-products-id-provision-fields-values-case-related-b",
    { recordingsDir }
  );
  const valuesHost = getFixtureBody(
    "get-orders-id-products-id-provision-fields-values-case-related-host",
    { recordingsDir }
  );
  const hostingConfig = getFixtureBody(
    "get-basket-id-products-id-basket-id-basket-product-id-case-related-host",
    { recordingsDir }
  );
  const hostingDefs = getFixtureBody(
    "get-basket-products-id-provision-fields-case-related-host",
    { recordingsDir }
  );

  server?.use(
    // the rich basket + its (registrant-only) provision-check failure
    http.get("*/api/orders/current", () =>
      HttpResponse.json(currentBody as object)
    ),
    http.patch("*/api/orders/:oid/provision_fields/values/check", () =>
      HttpResponse.json(checkBody as object, { status: 409 })
    ),
    // each product's provisionFields VALUES — dispatched by the recorded bpid so
    // the hosting product's `domain` cross-reference and each domain's sld land
    // on the right product (the id-masked identity alone would collapse them).
    http.get(
      "*/api/orders/:oid/products/:bpid/provision_fields/values",
      ({ params }) => {
        if (params.bpid === ids.domainA)
          return HttpResponse.json(valuesA as object);
        if (params.bpid === ids.domainB)
          return HttpResponse.json(valuesB as object);
        if (params.bpid === ids.hosting)
          return HttpResponse.json(valuesHost as object);
        return undefined;
      }
    ),
    // the hosting product config + its own field defs, so configure(hosting)
    // resolves against ITS blueprint; the two domains fall through to the base
    // domain config (correct — they ARE domains).
    http.get("*/api/basket/:bid/products/:bpid", ({ params }) =>
      params.bpid === ids.hosting
        ? HttpResponse.json(hostingConfig as object)
        : undefined
    ),
    http.get("*/api/basket/products/:pid/provision_fields", ({ params }) =>
      params.pid === ids.hostingProduct
        ? HttpResponse.json(hostingDefs as object)
        : undefined
    )
  );

  await useSessionStore().useActions().isReady();
  const basket = useBasket();
  basket.clear();
  const settled = await basket.isReady();
  if (!settled) {
    throw new Error(
      `bootConfiguredBasket: useBasket did not settle (state: ${JSON.stringify(
        basket.state.value.value
      )})`
    );
  }
  return { basket, ids };
}

