// The slds the CONFIGURED cross-referenced capture seats on each domain (see
// product-setup.fixtures.ts). Each becomes the domain's `service_identifier`
// (`<sld>.<tld>`); asserting a similar product keeps its OWN sld proves the
// provisionFields-only propagation never clobbers across products.
const SLD_A = "fixturegenalpha"; // DOMAIN_AU → fixturegenalpha.au
const SLD_B = "fixturegenbeta"; // DOMAIN_ORG → fixturegenbeta.org

