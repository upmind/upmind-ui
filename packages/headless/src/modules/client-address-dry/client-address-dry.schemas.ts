export function useUischema({
  id
}: Pick<SchemaLookups, "id"> = {}): UISchemaElement {
  const schema = {
    type: "VerticalLayout",
    elements: [
      useUischemaDefinitions({ id }),
      // D-ADDR-3 — restored control (baseline commented this field out
      // entirely alongside its schema counterpart).
      {
        type: "Control",
        scope: "#/properties/type",
        i18n: "form.address_type"
      }
    ]
  };

  return schema as UISchemaElement;
}
