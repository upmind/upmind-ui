/** @internal */
import {
  CLIENT_PHONE_DRY_TYPES,
  DEFAULT_PHONE_TYPE
} from "./client-phone-dry.types";
import { map } from "lodash-es";
import type { JsonSchema7, UISchemaElement } from "@jsonforms/core";
import type { ICountry } from "@upmind-automation/types";

