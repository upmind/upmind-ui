export const usePlaceSchema = ({ countries, regions, types }: PlaceContext) => {
  const schema = {
    type: "object",
    title: "Address Fields",
    required: ["address_1", "city", "country_id", "postcode"],
    properties: {
      id: {
        type: ["integer", "null"],
        title: "ID",
        description: "The AutoGenerated ID of this Place/Address.",
        readOnly: true
      },
      // ---
      address_1: {
        type: "string",
        title: "Address Line 1"
      },
      address_2: {
        type: ["string", "null"],
        title: "Address Line 2"
      },
      city: {
        type: "string",
        title: "City"
      },
      postcode: {
        type: "string",
        title: "Postcode"
      },
      region_id: {
        type: ["string", "null"],
        title: "Region",
        oneOf: !regions?.length
          ? undefined
          : map(regions, item => {
              return {
                const: item.id,
                title: item.name
              };
            })
      },

      // not sure this is ever used, but it is in the type definition
      state: {
        type: ["string", "null"],
        title: "State"
      },

      country_id: {
        type: "string",
        title: "Country",
        oneOf: !countries?.length
          ? undefined
          : map(countries, item => {
              return {
                const: item.id,
                title: item.name
              };
            })
      },

      // ---

      default: {
        type: ["boolean", "null"],
        title: "Make this the default address?"
      },

      name: {
        type: ["string", "null"],
        title: "Reference Name"
      },

      type: {
        type: ["number", "null"],
        title: "Address Type",
        oneOf: !types?.length
          ? undefined
          : map(types, item => {
              return {
                const: item.key,
                title: item.value
              };
            })
      }
    }
  };

  // if (id) {
  //   schema.required.push("name");
  //   schema.required.push("type");
  // }

  return schema as JsonSchema;
};

