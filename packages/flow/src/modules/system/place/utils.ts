export const usePlaceModelParser = (schema: JsonSchema, values: IAddress) => {
  const model = reduce(
    schema.properties,
    (result, field, key) => {
      const value = get(values, key, field?.const || field?.default);
      set(result, key, value);
      return result;
    },
    {}
  );
  return model as IAddress;
};
