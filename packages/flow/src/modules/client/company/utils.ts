export const useSchema = ({ addresses, emails, phones, baseModel }) => {
  const choices = {
    addresses: addresses().getItems(),
    emails: emails().getItems(),
    phones: phones().getItems()
  };

  const schema = {
    type: "object",
    title: "Address Fields",
    required: ["name", "address_id", "email_id"],
    properties: {
      id: {
        type: ["string", "null"],
        title: "ID",
        description: "The AutoGenerated ID of this Company.",
        readOnly: true
      },

      // ---
      name: {
        type: ["string", "null"],
        title: "Name"
      },

      address_id: {
        type: ["string", "null"],
        title: "Address",
        // isLookup: addresses,
        default: baseModel.address_id,
        enum: !choices?.addresses?.length
          ? undefined
          : map(choices?.addresses, "id"),
        lookup: addresses
      },

      email_id: {
        type: ["string", "null"],
        title: "Email",
        // isLookup: emails,
        default: baseModel.email_id,
        enum: !choices?.emails?.length ? undefined : map(choices?.emails, "id"),
        lookup: emails
      },

      phone_id: {
        type: ["string", "null"],
        title: "Phone",
        // isLookup: phones,
        default: baseModel.phone_id,
        enum: !choices?.phones?.length ? undefined : map(choices?.phones, "id"),
        lookup: phones
      },

      reg_number: {
        type: ["string", "null"],
        title: "Registrration number"
      },
      vat_number: {
        type: ["string", "null"],
        title: "Registered tax/VAT id"
      },
      vat_percent: {
        type: ["string", "null"],
        title: "VAT percent"
      },

      // ---

      default: {
        type: ["boolean", "null"],
        title: "Make this the default company?"
      }
    }
  };

  // if (id) {
  //   schema.required.push("name");
  //   schema.required.push("type");
  // }

  return schema as JsonSchema;
};

