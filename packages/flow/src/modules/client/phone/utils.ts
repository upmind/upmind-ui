export const spawnItem = (model?: IPhone) => {
  try {
    const name = get(model, "id", uniqueId("item_"));
    debugger;
    return spawn(
      itemMachine
        .withConfig({
          actions,
          services
        })
        .withContext({ model }),
      {
        name,
        sync: true
      }
    );
  } catch (err) {
    console.error("PhoneListings", "spawnItem", { model });
  }
};
