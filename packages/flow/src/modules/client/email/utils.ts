export const useModelParser = (schema: JsonSchema, values: IEmail) => {
  const model = reduce(
    schema.properties,
    (result, field, key) => {
      const value = get(values, key, field?.const || field?.default);
      set(result, key, value);
      return result;
    },
    {}
  );

  return defaultsDeep(model, values) as IEmail;
};

// --------------------------------------------------------

export const spawnItem = (model?: IEmail) => {
  try {
    const name = get(model, "id", uniqueId("item_"));
    return spawn(
      itemMachine
        .withConfig({
          actions,
          services
        })
        .withContext({ model }),
      {
        name,
        sync: true
      }
    );
  } catch (err) {
    console.error("EmailListings", "spawnItem", { model });
  }
};
