// --------------------------------------------------------

export const useSchema = context => {
  const schema = {
    type: "object",
    title: "Address Fields",
    required: ["email"],
    properties: {
      id: {
        type: ["string", "null"],
        title: "ID",
        description: "The AutoGenerated ID of this Email.",
        readOnly: true
      },

      // ---
      type: {
        type: "number",
        const: 1
      },

      email: {
        type: ["string", "null"],
        format: "email",
        title: "Email"
      },

      // ---

      default: {
        type: ["boolean", "null"],
        title: "Make this the default email?"
      }
    }
  };

  return schema as JsonSchema;
};

