export const useModelParser = (
  schema: JsonSchema,
  values: IAddress,
  baseModel: IAddress
) => {
  const model = reduce(
    schema.properties,
    (result, field, key) => {
      const value = get(
        values,
        key,
        field?.const || field?.default || get(baseModel, key)
      );
      set(result, key, value);
      return result;
    },
    {}
  );

  return defaultsDeep(model, values) as IAddress;
};

